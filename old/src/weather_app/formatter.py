def weather_code_to_korean(code: int) -> str:
    return _KOREAN.get(code, "알 수 없음")


def weather_code_to_emoji(code: int) -> str:
    return _EMOJI.get(code, "🌡️")


def weather_code_to_theme(code: int) -> str:
    """배경 그라데이션 테마 키. 맑음/구름/비/눈/뇌우 5단계."""
    if code in (0, 1):
        return "sunny"
    if code in (2, 3, 45, 48):
        return "cloudy"
    if code in (71, 73, 75, 77, 85, 86):
        return "snow"
    if code in (95, 96, 99):
        return "storm"
    return "rain"
